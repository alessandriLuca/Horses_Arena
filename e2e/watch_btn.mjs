import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const base = "http://127.0.0.1:8787";
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = [];
page.on("console", (m) => { if (m.type() !== "log") errs.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => errs.push("PAGE " + e.message));
await page.goto(base + "/");
await page.waitForSelector("#rName");
await page.fill("#rName", "W"+"x");
await page.fill("#rStable", "Scuderia W " + Math.floor(Math.random() * 1e6));
await page.click("#reg");
await page.waitForSelector(".hero h1");
const token = await page.evaluate(() => localStorage.getItem("ha_token"));
const api = (p, b) => page.evaluate(async ([p, b, token]) => (await fetch("/api" + p, { method: b ? "POST" : "GET", headers: { "content-type": "application/json", authorization: "Bearer " + token }, body: b ? JSON.stringify(b) : undefined })).json(), [p, b, token]);
const m = await api("/market");
const h = m.horses.filter((x) => !x.canRace && !x.ownerId).sort((a, b) => a.price - b.price)[0];
await api("/market/buy", { horseId: h.id });
const f = await api("/friendly", { horseId: h.id, bots: 5, distance: 1000 });
await page.goto(base + "/corsa/" + f.raceId);
await page.waitForSelector("#watch", { timeout: 150000 });
await page.waitForTimeout(1000);
await page.click("#watch");
await page.waitForTimeout(8000);
await page.screenshot({ path: "e2e/shots/watchbtn.png" });
console.log("viewer visible:", await page.isVisible(".viewer-stage canvas"));
console.log(errs.slice(0, 15).join("\n"));
await browser.close();
