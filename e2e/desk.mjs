import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const base = process.argv[2] ?? "http://127.0.0.1:8787";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 2, locale: "it-IT" });
await ctx.addInitScript(() => localStorage.setItem("ha_settings", JSON.stringify({ lang: "it", voice: false })));
const page = await ctx.newPage();
await page.goto(base + "/");
await page.waitForSelector("#rName");
await page.screenshot({ path: "e2e/shots/desk_welcome.png" });
await page.fill("#rName", "Luca");
await page.fill("#rStable", "Scuderia Sakura " + Math.floor(Math.random() * 1e5));
await page.click("#reg");
await page.waitForSelector(".hero h1");
await page.evaluate(async () => { const t = localStorage.getItem("ha_token"); await fetch("/api/tutorial", { method: "POST", headers: { "content-type": "application/json", authorization: "Bearer " + t }, body: JSON.stringify({ step: "__skip" }) }); });
await page.goto(base + "/mercato");
await page.waitForSelector("[data-buy]");
await page.waitForTimeout(600);
await page.screenshot({ path: "e2e/shots/desk_market.png" });
await page.click("[data-buy]");
await page.click("[data-ok]");
await page.waitForSelector(".portrait.big");
await page.waitForTimeout(800);
await page.screenshot({ path: "e2e/shots/desk_horse.png" });
await page.goto(base + "/bacheca");
await page.waitForTimeout(1200);
await page.screenshot({ path: "e2e/shots/desk_offers.png" });
await page.goto(base + "/mercato-nero");
await page.waitForTimeout(1200);
await page.screenshot({ path: "e2e/shots/desk_crime.png" });
await browser.close();
